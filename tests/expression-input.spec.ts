import { test, expect } from '@playwright/test';
test('線図は指数と掛け算を整形し、入力とSVG保存は同じ式を保持する', async ({ page })=>{
 await page.goto('/');
 await page.getByRole('button',{name:'伝達関数 G',exact:true}).click();
 const source='s^3+a*s^2+b*s+1';
 await page.getByLabel('選択ブロックの分母').fill(source);
 await expect(page.locator('.diagram-node').filter({has:page.locator('text.node-label',{hasText:'G'})}).locator('.node-expression').last()).toHaveText('s³+a×s²+b×s+1');
 await expect(page.getByLabel('選択ブロックの分母')).toHaveValue(source);
 await page.getByRole('button',{name:'編集欄を閉じる'}).click();
 await page.getByRole('button',{name:'保存・読込',exact:true}).click();
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'SVG保存',exact:true}).click();
 const file=await (await download).path();
 const {readFile}=await import('node:fs/promises');
 expect(await readFile(file!,'utf8')).toContain('s³+a×s²+b×s+1');
 await page.reload();
 await page.getByRole('button',{name:'伝達関数 G',exact:true}).click();
 await expect(page.getByLabel('選択ブロックの分母')).toHaveValue(source);
});
test('電卓キーは分子・分母の選択とカーソル位置に入力し、文字も選べる',async({page},info)=>{
 await page.goto('/');
 await page.getByRole('button',{name:'伝達関数 G',exact:true}).click();
 const editor=page.getByRole('region',{name:'ブロックを編集'});
 if(info.project.name==='desktop')await editor.getByRole('button',{name:'電卓キーを表示',exact:true}).click();
 const numerator=page.getByLabel('選択ブロックの分子');
 await numerator.click();
 await editor.getByRole('button',{name:'入力欄をクリア'}).click();
 for(const key of ['2','×','s'])await editor.getByRole('button',{name:key,exact:true}).click();
 await expect(numerator).toHaveValue('2*s');
 await numerator.evaluate((el:HTMLInputElement)=>el.setSelectionRange(1,1));
 await editor.getByRole('button',{name:'+' ,exact:true}).click();
 await expect(numerator).toHaveValue('2+*s');
 await editor.getByRole('button',{name:'1文字削除'}).click();
 await expect(numerator).toHaveValue('2*s');
 const denominator=page.getByLabel('選択ブロックの分母');
 await denominator.click();
 await editor.getByRole('button',{name:'入力欄をクリア'}).click();
 await editor.getByLabel('文字係数を挿入').selectOption('R');
 await editor.getByRole('button',{name:'÷',exact:true}).click();
 await editor.getByLabel('文字係数を挿入').selectOption('L');
 await expect(denominator).toHaveValue('R/L');
 await expect(numerator).toHaveValue('2*s');
 await expect(denominator).toHaveAttribute('inputmode','none');
 await editor.getByRole('button',{name:'キーボード入力に切替'}).click();
 await expect(denominator).toHaveAttribute('inputmode','text');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
